"""
Детерминированный выбор лидера роя.
Использует SHA-256, чтобы результат был одинаковым на всех машинах.
"""
import hashlib

def select_leader(node_id: str, block_number: int, total_nodes: int) -> int:
    """
    Выбирает лидера роя детерминированным способом на основе SHA-256 хэша.

    Генерирует уникальный хэш на основе ID узла и номера блока,
    затем использует его для детерминированного выбора лидера из общего количества узлов.
    Этот подход обеспечивает консистентность выбора лидера на разных машинах,
    так как SHA-256 является криптографически стойкой хэш-функцией.

    Args:
        node_id: Уникальный строковый идентификатор текущего узла.
        block_number: Целочисленный номер текущего блока или раунда, который
                      используется для изменения seed хэша.
        total_nodes: Общее количество узлов в рое, от которого зависит диапазон
                     индекса лидера (от 0 до total_nodes-1).

    Returns:
        Индекс узла-лидера (целое число от 0 до total_nodes-1).
    """
    seed: bytes = f"{node_id}:{block_number}".encode('utf-8')
    h: str = hashlib.sha256(seed).hexdigest()
    # Преобразуем хэш (шестнадцатеричную строку) в целое число и берём модуль
    # от общего количества узлов, чтобы получить индекс в заданном диапазоне.
    leader_index: int = int(h, 16) % total_nodes
    return leader_index